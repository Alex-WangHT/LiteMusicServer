await send(`/api/playlists/${list.id}/items`, 'PUT', { video_ids: [second.id, job.id] });
assert.deepEqual((await (await send(`/api/playlists/${list.id}`, 'GET')).json()).videos.map(v => v.id), [second.id, job.id]);
await send(`/api/videos/${second.id}`, 'DELETE');
const rotated = await (await send('/api/me/key', 'POST')).json();
assert.equal((await send('/api/me', 'GET')).status, 401);
assert.equal((await fetch(audio)).status, 401);
admin = { Authorization: `Bearer ${rotated.key}` };
assert.equal((await send('/api/me', 'GET')).status, 200);
assert.equal((await send(`/api/videos/${job.id}`, 'GET')).status, 200);
const shared = await (await send('/api/videos', 'POST', { url: `https://www.bilibili.com/video/${id}` }, other)).json();
assert.equal(shared.id, job.id);
const fresh = await (await send(`/api/videos/${job.id}/playback`, 'POST')).json();
await send(`/api/videos/${job.id}`, 'DELETE');
assert.equal((await fetch(fresh.audio_url)).status, 401);
assert.equal((await send(`/api/videos/${job.id}/audio`, 'HEAD', undefined, other)).status, 200);
assert.deepEqual((await (await send(`/api/playlists/${list.id}`, 'GET')).json()).videos, []);
await send(`/api/videos/${job.id}`, 'DELETE', undefined, other);
await send(`/api/playlists/${list.id}`, 'DELETE');
console.log('PASS: user isolation, admin separation, playlist order, ownership, rotation, revoked tickets, shared file isolation, cascade removal');
