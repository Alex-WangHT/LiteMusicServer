import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
const base = process.env.WORKER_URL || 'http://127.0.0.1:8787';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Synthetic integration tests may only run locally');
const root = { Authorization: `Bearer ${process.env.ADMIN_TOKEN}` };
let admin;
const downloader = { Authorization: `Bearer ${process.env.DOWNLOADER_TOKEN}` };
const send = (path, method, data, headers = admin) => fetch(base + path, { method, headers: { ...headers, 'Content-Type': 'application/json' }, body: data === undefined ? undefined : JSON.stringify(data) });
const userA = await (await send('/api/admin/users', 'POST', { name: 'integration-A' }, root)).json();
const userB = await (await send('/api/admin/users', 'POST', { name: 'integration-B' }, root)).json();
admin = { Authorization: `Bearer ${userA.key}` };
const other = { Authorization: `Bearer ${userB.key}` };
assert.equal((await send('/api/videos', 'GET', undefined, root)).status, 401);
const id = `BV${randomBytes(5).toString('hex')}`;
let response = await send('/api/videos', 'POST', { url: `https://www.bilibili.com/video/${id}` }, {});
assert.equal(response.status, 401);
response = await send('/api/videos', 'POST', { url: 'http://127.0.0.1/private' });
assert.equal(response.status, 400);
for (const url of ['https://www.youtube.com/watch?v=u5NiDaaq-XM', 'https://www.tiktok.com/@test/video/7380000000000000000']) {
  assert.equal((await send('/api/videos', 'POST', { url })).status, 400);
}
const douyin = await (await send('/api/videos', 'POST', { url: 'https://www.douyin.com/video/7380000000000000000' })).json();
assert.equal(douyin.platform, 'douyin');
const douyinDuplicate = await (await send('/api/videos', 'POST', { url: 'https://www.iesdouyin.com/share/video/7380000000000000000/' })).json();
assert.equal(douyin.id, douyinDuplicate.id);
await send(`/api/videos/${douyin.id}`, 'DELETE');
const job = await (await send('/api/videos', 'POST', { url: `https://www.bilibili.com/video/${id}` })).json();
const duplicate = await (await send('/api/videos', 'POST', { url: `https://www.bilibili.com/video/${id}?p=1&spm_id_from=test` })).json();
assert.equal(job.id, duplicate.id);
const claimResponses = await Promise.all([send('/internal/jobs/claim', 'POST', undefined, downloader), send('/internal/jobs/claim', 'POST', undefined, downloader)]);
const claims = await Promise.all(claimResponses.map(r => r.json()));
const claimed = claims.map(c => c.job).filter(Boolean);
assert.equal(claimed.length, 1, 'Run integration tests with an otherwise empty queue and stopped downloader');
assert.equal(claimed[0].id, job.id);
const lease = { ...downloader, 'X-Lease-Token': claimed[0].lease_token };
response = await send(`/internal/jobs/${job.id}/metadata`, 'POST', { title: 'Integration fixture (not real audio)', duration: 2 }, { ...downloader, 'X-Lease-Token': 'stale' });
assert.equal(response.status, 409);
response = await send(`/internal/jobs/${job.id}/metadata`, 'POST', { title: 'Integration fixture (not real audio)', duration: 2 }, lease);
assert.equal(response.status, 200);
const bytes = Buffer.from(Array.from({ length: 1024 }, (_, i) => i % 256));
response = await fetch(`${base}/internal/jobs/${job.id}/audio`, { method: 'PUT', headers: { ...lease, 'Content-Type': 'audio/mp4', 'Content-Length': String(bytes.length) }, body: bytes });
assert.equal(response.status, 200, await response.text());
assert.equal((await send(`/api/videos/${job.id}`, 'GET', undefined, other)).status, 404);
assert.equal((await send(`/api/videos/${job.id}/playback`, 'POST', undefined, other)).status, 404);
assert.equal((await send(`/api/videos/${job.id}`, 'DELETE', undefined, other)).status, 404);
assert.equal((await fetch(`${base}/api/videos/${job.id}/audio`)).status, 401);
const audio = (await (await send(`/api/videos/${job.id}/playback`, 'POST')).json()).audio_url;
response = await fetch(audio);
assert.equal(response.status, 200);
assert.deepEqual(Buffer.from(await response.arrayBuffer()), bytes);
const etag = response.headers.get('etag');
response = await fetch(audio, { headers: { Range: 'bytes=100-199', Origin: 'https://player.example' } });
assert.equal(response.status, 206);
assert.equal(response.headers.get('content-range'), 'bytes 100-199/1024');
assert.equal(response.headers.get('access-control-allow-origin'), '*');
assert.deepEqual(Buffer.from(await response.arrayBuffer()), bytes.subarray(100, 200));
response = await fetch(audio, { method: 'HEAD' });
assert.equal(response.headers.get('content-length'), '1024');
assert.equal((await response.arrayBuffer()).byteLength, 0);
response = await fetch(audio, { headers: { Range: 'bytes=-20' } });
assert.deepEqual(Buffer.from(await response.arrayBuffer()), bytes.subarray(-20));
response = await fetch(audio, { headers: { Range: 'bytes=1024-' } });
assert.equal(response.status, 416);
assert.equal(response.headers.get('content-range'), 'bytes */1024');
response = await fetch(audio, { headers: { 'If-None-Match': etag } });
assert.equal(response.status, 304);
response = await fetch(audio, { headers: { Range: 'bytes=0-1', 'If-Range': '"old"' } });
assert.equal(response.status, 200);
await response.arrayBuffer();
response = await send(`/internal/jobs/${job.id}/fail`, 'POST', { error: 'stale result' }, lease);
assert.equal(response.status, 409);
console.log('PASS: auth, URL validation, deduplication, concurrent claim, stale lease, upload, GET, HEAD, 206, suffix, 416, ETag, If-Range, CORS');
console.log(`Synthetic fixture id: ${job.id} (not playable audio; local test only)`);
const list = await (await send('/api/playlists', 'POST', { name: 'test-list' })).json();
assert.equal((await send(`/api/playlists/${list.id}/items`, 'PUT', { video_ids: [job.id] })).status, 200);
assert.equal((await send(`/api/playlists/${list.id}`, 'GET', undefined, other)).status, 404);
assert.equal((await send(`/api/playlists/${list.id}`, 'PATCH', { name: 'steal' }, other)).status, 404);
